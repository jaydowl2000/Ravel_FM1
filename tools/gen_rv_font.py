"""Ravel's screen fonts as a C header: true pixel fonts, no smoothing, every edge a hard pixel. The glyphs are
in tools/pixel_font_data.py (made once by tools/extract_pixel_fonts.py from X11 misc-fixed 6x9 and GNU Unifont),
so building needs no font files. Three roles: T (labels, the footer), XS (lists, names), B (values, titles,
readouts). Same C layout as before: 4 bits a pixel, a set pixel is 15.

  gen_rv_font.py OUT.h
"""
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
from pixel_font_data import F6X9, UNI16

# role, glyph set, glyph height, letter advance (px), line height (px), shift down (px) to put the baseline where the layouts expect it
ROLES = [("T", F6X9, 9, 6, 12, 1), ("XS", F6X9, 9, 6, 14, 2), ("B", UNI16, 16, 8, 18, -2)]


def render(src, gh, adv, lh, dy):
    glyphs = []
    for c in range(32, 96):
        rows = [[0] * 0 for _ in range(lh)]
        grid = [[0] * len(src[c][0]) for _ in range(lh)]
        for y, r in enumerate(src[c]):
            if 0 <= y + dy < lh:
                grid[y + dy] = [15 if ch == "#" else 0 for ch in r]
        cols = [x for x in range(len(grid[0])) if any(grid[y][x] for y in range(lh))]
        if not cols:
            glyphs.append((adv, 0, 0, []))
            continue
        x0, x1 = cols[0], cols[-1] + 1
        glyphs.append((adv, x0, x1 - x0, [grid[y][x] for y in range(lh) for x in range(x0, x1)]))
    return lh, glyphs


def main(out):
    lines = ["/* generated by tools/gen_rv_font.py: pixel fonts, 4 bits per pixel */",
             "#pragma once", "#include <stdint.h>", ""]
    total = 0
    for name, src, gh, adv, lh, dy in ROLES:
        h, glyphs = render(src, gh, adv, lh, dy)
        data, offs = [], []
        for adv, bx, bw, g in glyphs:
            offs.append(len(data))
            bpr = (bw + 1) // 2
            for y in range(h):
                row = g[y * bw:(y + 1) * bw] + [0]
                for x in range(0, bpr * 2, 2):
                    data.append((row[x] << 4) | row[x + 1])
        total += len(data) + 4 * len(glyphs)
        lines.append(f"static const uint8_t FONT_{name}_DATA[{max(1, len(data))}] = {{")
        for i in range(0, len(data), 24):
            lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
        lines.append("};")
        lines.append(f"static const uint16_t FONT_{name}_OFF[{len(offs)}] = {{" + ", ".join(map(str, offs)) + "};")
        lines.append(f"static const uint8_t FONT_{name}_ADV[{len(glyphs)}] = {{" + ", ".join(str(a) for a, _, _, _ in glyphs) + "};")
        lines.append(f"static const int8_t FONT_{name}_BX[{len(glyphs)}] = {{" + ", ".join(str(b) for _, b, _, _ in glyphs) + "};")
        lines.append(f"static const uint8_t FONT_{name}_BW[{len(glyphs)}] = {{" + ", ".join(str(w) for _, _, w, _ in glyphs) + "};")
        lines.append(f"static const rv_font_t FONT_{name} = {{ {h}, 32, 95, FONT_{name}_ADV, FONT_{name}_BX, FONT_{name}_BW, FONT_{name}_OFF, FONT_{name}_DATA }};")
        lines.append("")
    print(f"fonts: {total} B")
    Path(out).write_text("\n".join(lines))


if __name__ == "__main__":
    main(sys.argv[1])
